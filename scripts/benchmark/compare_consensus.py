#!/usr/bin/env python

import argparse
import numpy as np
import matplotlib.pyplot as plt

def count_bases(sequence) -> dict:
    base_counts = {'A': 0, 'T': 0, 'G': 0, 'C': 0, 'N': 0}
    for base in sequence:
        base = base.upper()
        if base in base_counts:
            base_counts[base] += 1
    return base_counts

def count_bases_in_fasta(fasta_file) -> dict:
    base_counts = {'A': 0, 'T': 0, 'G': 0, 'C': 0, 'N': 0}
    
    with open(fasta_file, 'r') as file:
        for line in file:
            if not line.startswith('>'):
                sequence = line.strip()
                sequence_base_counts = count_bases(sequence)
                for base, count in sequence_base_counts.items():
                    base_counts[base] += count
    base_counts["total"] = sum(base_counts.values())
    
    return base_counts

def plot_base_counts(tool1_counts, tool2_counts, tools) -> None:
    bases = ['A', 'T', 'G', 'C', 'N']
    tool1_counts_list = [tool1_counts[base] for base in bases]
    tool2_counts_list = [tool2_counts[base] for base in bases]

    x = np.arange(len(bases))
    width = 0.35

    plt.style.use('ggplot')

    fig, ax = plt.subplots()

    rects1 = ax.bar(x - width/2, tool1_counts_list, width, label=f"{tools[0]}: {tool1_counts['total']}")
    rects2 = ax.bar(x + width/2, tool2_counts_list, width, label=f"{tools[1]}: {tool2_counts['total']}")


    ax.set_ylabel('Counts')

    total_difference = tool1_counts['total'] - tool2_counts['total']
    title_text = f'Counts of Bases per Tool'
    ax.set_title(title_text)


    ax.set_xticks(x)
    ax.set_xticklabels(bases)
    ax.legend()

    # Adding labels for the difference between bars
    for i in range(len(bases)):
        diff = tool1_counts_list[i] - tool2_counts_list[i]
        if diff > 0:
            ax.text(x[i] - width/2, max(tool1_counts_list[i], tool2_counts_list[i]), f'{tools[0]} up: {diff}', ha='center', rotation=20)
        elif diff < 0:
            ax.text(x[i] + width/2, max(tool1_counts_list[i], tool2_counts_list[i]), f'{tools[1]} up: {abs(diff)}', ha='center', rotation=20)



    plt.savefig("base_count_between_tools.jpg")

def parse_args():
    parser = argparse.ArgumentParser(
        description="Script to compare consensus sequences generated from the same reference genome by two different methodologies"
    )
    parser.add_argument(
        "--fasta1",
        "-1",
        help="Fasta file for consensus sequence generated by the first method",
        default="/lustre/scratch126/pam/teams/team230/sd28/test/mm2b_no_indel/31663_7#10_BWA/31663_7#10.mfa",
    )
    parser.add_argument(
        "--fasta2",
        "-2",
        default="/lustre/scratch126/pam/teams/team230/sd28/test/comparemm2b_strain/OLD_31663_7#10_Streptococcus_agalactiae_NGBS128_GCF_001552035_1.fa",
        help="Fasta file for consensus sequence generated by the second method",
    )
    parser.add_argument(
        "--method1",
        "-m",
        default='mm2b_no_indel',
        help="Label for first consensus sequences generation method",
    )
    parser.add_argument(
        "--method2",
        "-M",
        default='BWA_new_SM',
        help="Label for second consensus sequences generation method",
    )
    return parser.parse_args()

if __name__ == "__main__":

    args = parse_args()

    tool1_counts = count_bases_in_fasta(args.fasta1)
    tool2_counts = count_bases_in_fasta(args.fasta2)
    
    plot_base_counts(tool1_counts, tool2_counts, [args.method1, args.method2])